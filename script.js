// --------------------------------------------------
// Create Graph
// --------------------------------------------------

function createGraph() {

    const graph = {};

    devices.forEach(device => {
        graph[device.id] = [];
    });

    connections.forEach(connection => {

        graph[connection.from].push({
            node: connection.to,
            cost: connection.cost
        });

        graph[connection.to].push({
            node: connection.from,
            cost: connection.cost
        });
    });

    return graph;
}

// --------------------------------------------------
// Dijkstra Algorithm
// --------------------------------------------------

function dijkstra(start, end) {

    const graph = createGraph();

    const distances = {};
    const previous = {};
    const visited = new Set();

    devices.forEach(device => {
        distances[device.id] = Infinity;
        previous[device.id] = null;
    });

    distances[start] = 0;

    while (visited.size < devices.length) {

        let current = null;
        let smallestDistance = Infinity;

        devices.forEach(device => {

            if (
                !visited.has(device.id) &&
                distances[device.id] < smallestDistance
            ) {
                smallestDistance = distances[device.id];
                current = device.id;
            }
        });

        if (current === null) {
            break;
        }

        if (current === end) {
            break;
        }

        visited.add(current);

        graph[current].forEach(neighbor => {

            if (visited.has(neighbor.node)) {
                return;
            }

            const newDistance =
                distances[current] + neighbor.cost;

            if (newDistance < distances[neighbor.node]) {

                distances[neighbor.node] = newDistance;
                previous[neighbor.node] = current;
            }
        });
    }

    // Build path
    const path = [];

    let current = end;

    while (current !== null) {

        path.unshift(current);

        current = previous[current];
    }

    if (path[0] !== start) {
        return {
            path: [],
            distance: Infinity
        };
    }

    return {
        path: path,
        distance: distances[end]
    };
}

// --------------------------------------------------
// Find Shortest Path
// --------------------------------------------------

function findShortestPath() {

    if (devices.length < 2) {
        alert("Add devices first.");
        return;
    }

    const source = Number(document.getElementById("source").value);
    const destination = Number(
        document.getElementById("destination").value
    );

    if (source === destination) {
        alert("Source and destination must be different.");
        return;
    }

    const result = dijkstra(source, destination);

    if (result.path.length === 0) {

        document.getElementById("pathResult").textContent =
            "❌ No route available.";

        document.getElementById("costResult").textContent = "";

        shortestPath = [];

        drawNetwork();

        return;
    }

    shortestPath = result.path;

    const pathNames = result.path.map(id => {
        return devices[id].name;
    });

    document.getElementById("pathResult").textContent =
        "Path: " + pathNames.join(" → ");

    document.getElementById("costResult").textContent =
        "Total Cost: " + result.distance;

    drawNetwork();
}

// --------------------------------------------------
// Check whether connection belongs to shortest path
// --------------------------------------------------

function isPathConnection(from, to) {

    for (let i = 0; i < shortestPath.length - 1; i++) {

        const a = shortestPath[i];
        const b = shortestPath[i + 1];

        if (
            (a === from && b === to) ||
            (a === to && b === from)
        ) {
            return true;
        }
    }

    return false;
}

// --------------------------------------------------
// Draw Network
// --------------------------------------------------

function drawNetwork() {

    ctx.clearRect(0, 0, canvas.width, canvas.height);

    // Draw connections
    connections.forEach(connection => {

        const from = devices[connection.from];
        const to = devices[connection.to];

        const active = isPathConnection(
            connection.from,
            connection.to
        );

        ctx.beginPath();

        ctx.moveTo(from.x, from.y);
        ctx.lineTo(to.x, to.y);

        ctx.strokeStyle = active ? "#16a34a" : "#94a3b8";

        ctx.lineWidth = active ? 6 : 3;

        ctx.stroke();

        // Cost
        const midX = (from.x + to.x) / 2;
        const midY = (from.y + to.y) / 2;

        ctx.fillStyle = "#111827";
        ctx.font = "bold 14px Arial";
        ctx.fillText(
            connection.cost,
            midX + 5,
            midY - 5
        );
    });

    // Draw devices
    devices.forEach(device => {

        const isPathNode =
            shortestPath.includes(device.id);

        ctx.beginPath();

        ctx.arc(
            device.x,
            device.y,
            30,
            0,
            Math.PI * 2
        );

        ctx.fillStyle =
            isPathNode ? "#16a34a" : "#2563eb";

        ctx.fill();

        ctx.strokeStyle = "#ffffff";
        ctx.lineWidth = 3;
        ctx.stroke();

        ctx.fillStyle = "white";
        ctx.font = "bold 14px Arial";
        ctx.textAlign = "center";
        ctx.textBaseline = "middle";

        ctx.fillText(
            device.name,
            device.x,
            device.y
        );

        ctx.textAlign = "left";
        ctx.textBaseline = "alphabetic";
    });
}

